/**
 * The single Material 3 theme for the whole app (Principle III). Provides color, typography, and
 * spacing tokens; adapts to the system light/dark setting.
 */
@Composable
fun FaceVerifyTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colors = if (darkTheme) DarkColors else LightColors
    CompositionLocalProvider(LocalSpacing provides Spacing()) {
        MaterialTheme(
            colorScheme = colors,
            typography = AppTypography,
            content = content,
        )
    }
}
